# 词 -> 同义词组（用于 O(1) 查找）
_LOOKUP: Dict[str, List[str]] = {}
for group in SYNONYM_GROUPS:
    for word in group:
        _LOOKUP.setdefault(word, [w for w in group if w != word])


def synonym_variants(text: str) -> List[str]:
    """返回给定症状文本（单个词/短语）的可替换变体列表（不含原文）。"""
    return _LOOKUP.get(text, [])


def build_query_variants(symptoms: List[str], max_variants: int = 2) -> List[List[str]]:
    """
    为症状列表生成最多 max_variants 个查询变体。

    规则（保持可解释、避免组合爆炸）：
    1. 仅对"命中同义词组"的症状做替换，最多取前 2 个可替换症状。
    2. 每个变体只替换一个症状，替换值为该症状的第一个同义词。
    3. 返回的变体与原文症状列表等长、其余项不变。
    """
    variants: List[List[str]] = []
    replaced = 0
    for i, s in enumerate(symptoms):
        if replaced >= max_variants:
            break
        alts = synonym_variants(s)
        if not alts:
            continue
        v = list(symptoms)
        v[i] = alts[0]
        variants.append(v)
        replaced += 1
    return variants
