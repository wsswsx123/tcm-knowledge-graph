"""
Few-shot Chain-of-Thought 提示词模板。

设计要点：
1. 每个三级 Agent 都有独立的 system 模板，明确其职责边界。
2. 通过 Few-shot 示例示范"逐步推理 -> 结构化输出"的思维链路。
3. 输出统一为严格 JSON，便于后续解析置信度并执行拒答机制。
4. 体质推理 Agent 的输出必须包含 confidence 字段，供主控 Agent 仲裁。

注意：模板使用 str.format 填充占位符，故所有示例 JSON 的花括号
必须转义为双花括号 {{ }}，避免被误解析为占位符。
"""
